//! The skills the binary carries, and the one act that shelves them.
//!
//! The bytes are compiled in, so every install channel - the archive,
//! the install script, npm, binstall, `cargo install` - carries the same
//! skills. They reach the shelf through [`install`] and nothing else:
//! staged as directories under a dot-prefixed directory the scan never
//! reads, then installed one by one, so the precheck, the atomic landing
//! and the store registration stay where §8-28 put them.
//!
//! Specified by `crates/city/spec/Library/Install.lean` §8-28c.

use std::collections::BTreeSet;
use std::path::Path;

use kernel::layout::CityLayout;
use kernel::{AxCode, AxError, B3Hash};

use super::install::{Installed, Slot, install};

/// The library section the shipped skills are filed under.
pub const SHIPPED_SECTION: &str = "shipped";

/// Where the skills are written out before each is installed: inside the
/// library, dot-prefixed, so the scan skips it.
const STAGING_DIR: &str = ".shipped";

/// Every file of every shipped skill as `<name>/<path>`, `/` between
/// segments, sorted, plus one root row with no `/` naming the licence
/// list that travels inside every skill directory; generated by
/// `crates/city/build.rs`.
const SHIPPED: &[(&str, &[u8])] = include!(concat!(env!("OUT_DIR"), "/shipped_skills.rs"));

/// Puts every shipped skill on the city library's `shipped` section.
///
/// Called once, when a city forms: a city that already exists is not
/// restocked, because a missing shipped skill may be one the User took
/// down. The bytes are written as shipped, line endings included.
///
/// # Errors
/// Whatever [`install`] refuses for any one skill - a different skill
/// already filed under its name among them - and `E_STORAGE_FATAL` when
/// the staging directory cannot be written or cleared.
pub fn shelve_shipped(
    city_root: &Path,
    register: &mut dyn FnMut(&[u8]) -> Result<B3Hash, AxError>,
) -> Result<Vec<Installed>, AxError> {
    let staging = CityLayout::new(city_root).library().join(STAGING_DIR);
    clear(&staging)?;
    let shelved = stage(&staging).and_then(|names| {
        let slot = Slot::library(SHIPPED_SECTION)?;
        names
            .into_iter()
            .map(|name| install(city_root, &slot, &staging.join(name), register))
            .collect::<Result<Vec<_>, _>>()
    });
    let cleared = clear(&staging);
    let installed = shelved?;
    cleared?;
    Ok(installed)
}

/// Writes every file of the table under `staging`, and answers the skill
/// names it wrote.
///
/// A row with no `/` is the licence list: it is written into every skill
/// directory, because the notice an adapted skill owes has to reach the
/// copy a city shelves and not only the release archive (D37).
fn stage(staging: &Path) -> Result<BTreeSet<&'static str>, AxError> {
    let names = SHIPPED
        .iter()
        .filter_map(|(path, _)| path.split_once('/').map(|(name, _)| name))
        .collect::<BTreeSet<&'static str>>();
    for (path, bytes) in SHIPPED {
        match path.split_once('/') {
            Some(_) => write(staging, path, bytes)?,
            None => {
                for name in &names {
                    write(staging, &format!("{name}/{path}"), bytes)?;
                }
            }
        }
    }
    Ok(names)
}

/// Writes one table row under `staging`, making its directories first.
fn write(staging: &Path, path: &str, bytes: &[u8]) -> Result<(), AxError> {
    let target = path
        .split('/')
        .fold(staging.to_path_buf(), |at, segment| at.join(segment));
    match target.parent() {
        Some(parent) => std::fs::create_dir_all(parent),
        None => Ok(()),
    }
    .and_then(|()| std::fs::write(&target, bytes))
    .map_err(|err| staging_failed("stage a shipped skill", &target, &err))
}

/// Removes the staging directory: it was never swapped in, so no reader
/// has seen it, and one a crash left behind is removed the same way.
fn clear(staging: &Path) -> Result<(), AxError> {
    match std::fs::remove_dir_all(staging) {
        Ok(()) => Ok(()),
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(err) => Err(staging_failed(
            "clear the shipped skill staging",
            staging,
            &err,
        )),
    }
}

fn staging_failed(action: &str, path: &Path, err: &std::io::Error) -> AxError {
    AxError::failure(
        AxCode::StorageFatal,
        action,
        format!("{}: {err}", path.display()),
    )
    .with_recovery(
        "free space on this disk and make the city directory writable, then form the city again",
    )
}

#[cfg(test)]
#[allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::indexing_slicing,
    reason = "test code"
)]
mod tests {
    use super::*;

    /// The notice an adapted skill owes has to reach the copy a city
    /// shelves, and three of the four install channels carry the binary
    /// and nothing else (`crates/city/spec/Library/Install.lean` D37).
    #[test]
    fn every_staged_skill_carries_the_licence_list() {
        let staged = tempfile::tempdir().unwrap();
        let names = stage(staged.path()).unwrap();
        let shared = SHIPPED.iter().find(|(path, _)| !path.contains('/'));
        assert!(shared.is_some(), "the table carries the licence list");
        let (_, licence) = shared.unwrap();
        assert!(!names.is_empty(), "the table carries a skill");
        for name in &names {
            let written = std::fs::read(staged.path().join(name).join("LICENSES.md")).unwrap();
            assert_eq!(written, *licence, "{name} carries the licence list it owes");
        }
    }
}
